/**
 * Build-time shader compiler.
 *
 * The runtime never parses or concatenates GLSL: this script reads the
 * modules once, injects feature defines, and emits `src/core/shader/generated.ts`
 * plus readable snapshots under `dist/shaders/`. Variants are selected by the
 * renderer from the generated map; a compile failure at runtime falls back to
 * the prebuilt base or minimal fallback program.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const moduleDir = path.join(root, 'src', 'core', 'shader', 'modules');

const MODULES = [
  'common',
  'geometry',
  'detail',
  'color',
  'portrait',
  'creative',
  'output',
  'main',
];

const VARIANTS = [
  { key: 'base', linear: false, mask: false, liquify: false },
  { key: 'base-linear', linear: true, mask: false, liquify: false },
  { key: 'beauty', linear: true, mask: true, liquify: false },
  { key: 'beauty-liquify', linear: true, mask: true, liquify: true },
  { key: 'base-liquify', linear: false, mask: false, liquify: true },
  { key: 'base-linear-liquify', linear: true, mask: false, liquify: true },
  { key: 'beauty-gamma', linear: false, mask: true, liquify: false },
  { key: 'beauty-gamma-liquify', linear: false, mask: true, liquify: true },
  { key: 'fallback', fallback: true },
];

function readModule(name) {
  return readFileSync(path.join(moduleDir, `${name}.glsl`), 'utf8');
}

/**
 * Strip comments and indentation without touching preprocessor line structure.
 * GLSL has no string literals, so a line comment can be removed safely.
 */
function minify(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((line) => line.replace(/\/\/.*$/, '').trim())
    .filter((line) => line.length > 0)
    .join('\n')
    .concat('\n');
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function variantSource(variant) {
  if (variant.fallback) return minify(readModule('fallback'));
  const defines = [];
  if (variant.linear) defines.push('#define AURUM_LINEAR 1');
  if (variant.mask) defines.push('#define AURUM_BEAUTY_MASK 1');
  if (variant.liquify) defines.push('#define AURUM_LIQUIFY 1');
  return minify(
    [
      ...defines,
      ...MODULES.map((name) => readModule(name)),
    ].join('\n'),
  );
}

function templateLiteral(value, label) {
  if (value.includes('`') || value.includes('${')) {
    throw new Error(`Shader ${label} contains a template-literal delimiter.`);
  }
  return `\`${value}\``;
}

export function buildShaderAssets({ quiet = false } = {}) {
  const vertex = minify(readModule('vertex'));
  const variants = VARIANTS.map((variant) => {
    const source = variantSource(variant);
    return {
      ...variant,
      source,
      bytes: Buffer.byteLength(source),
      hash: sha256(source),
      modules: variant.fallback ? ['fallback'] : MODULES,
    };
  });

  const lines = [
    '// Generated by scripts/build-shaders.mjs. Do not edit by hand.',
    '// Run `npm run build` (or `npm run build:shaders`) after changing modules.',
    '',
    `export const VERTEX_SOURCE = ${templateLiteral(vertex, 'vertex')};`,
    '',
    'export const SHADER_VARIANTS = {',
  ];
  for (const variant of variants) {
    lines.push(`  '${variant.key}': ${templateLiteral(variant.source, variant.key)},`);
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type ShaderVariantKey = keyof typeof SHADER_VARIANTS;');
  lines.push(
    'export const SHADER_VARIANT_KEYS: ShaderVariantKey[] = Object.keys(SHADER_VARIANTS) as ShaderVariantKey[];',
  );
  lines.push('');

  const generatedPath = path.join(root, 'src', 'core', 'shader', 'generated.ts');
  writeFileSync(generatedPath, lines.join('\n'));

  const snapshots = path.join(root, 'dist', 'shaders');
  mkdirSync(snapshots, { recursive: true });
  writeFileSync(path.join(snapshots, 'vertex.glsl'), vertex);
  const manifest = {
    vertex: { bytes: Buffer.byteLength(vertex), sha256: sha256(vertex) },
    variants: variants.map(({ source, ...rest }) => rest),
  };
  for (const variant of variants) {
    writeFileSync(path.join(snapshots, `${variant.key}.glsl`), variant.source);
  }
  writeFileSync(path.join(snapshots, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

  if (!quiet) {
    const total = variants.reduce((sum, variant) => sum + variant.bytes, 0);
    console.log(
      `Shader variants: ${variants.length} (${(total / 1024).toFixed(1)} KB GLSL) -> src/core/shader/generated.ts`,
    );
  }
  return { vertex, variants };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildShaderAssets();
}
